# make_w8_netcdf.R
#
# Build netcdf climate inputs + a netcdf base station file for the W8 test case,
# from the existing W8 ASCII base station clim (clim/w8_daily.{rain,tmax,tmin}).
# Layout mirrors the Ward gridmet inputs (Projects/CARB/Ward/clim/crop_agg_met_*.nc,
# clim/netcdf.base): dims [lon, lat, time], time = integer days since 1900-01-01,
# 2 lon cells x 1 lat cell.
#
# Cell 1 (base_station_id 101, the ID every W8 zone uses) holds the W8 data.
# Cell 2 (base_station_id 102) is a copy of the same data; it exists so the netcdf
# reader's grid-resolution calculation (nearest distance between stations) is
# exercised the way it is for real multi-cell inputs.
#
# Only tmax/tmin/rain are written: the default build does not define
# LIU_EXTEND_CLIM_VAR, so the other gridmet variables are never read.
#
# Units: temperature in degrees C (temperature_unit C), precip in mm
# (precip_multiplier 0.001), matching gridmet's mm precip.
#
# Run from the Testing/ directory:  Rscript clim/make_w8_netcdf.R

library(ncdf4)

clim_prefix = "clim/w8_daily"
out_dir = "clim"
base_out = "clim/w8_netcdf.base"

# Approximate HJ Andrews WS8 location (only needs to be self-consistent with the base file)
lons = c(-122.175000, -122.133333)
lat = 44.208333
res = 0.041667

read_ascii_clim = function(f) {
  lines = readLines(f)
  start = as.integer(strsplit(trimws(lines[1]), "\\s+")[[1]][1:3])
  vals = as.numeric(trimws(lines[-1]))
  vals = vals[!is.na(vals)]
  list(start = as.Date(sprintf("%04d-%02d-%02d", start[1], start[2], start[3])), vals = vals)
}

vars = list(
  tmax = list(file = paste0(clim_prefix, ".tmax"), name = "daily_maximum_temperature", units = "C", mult = 1),
  tmin = list(file = paste0(clim_prefix, ".tmin"), name = "daily_minimum_temperature", units = "C", mult = 1),
  rain = list(file = paste0(clim_prefix, ".rain"), name = "precipitation_amount", units = "mm", mult = 1000)
)

clim = lapply(vars, function(v) read_ascii_clim(v$file))
starts = unique(do.call(c, lapply(clim, `[[`, "start")))
lens = unique(sapply(clim, function(x) length(x$vals)))
stopifnot(length(starts) == 1, length(lens) == 1)

time_vals = as.integer(seq(starts, by = "day", length.out = lens) - as.Date("1900-01-01"))

for (v in names(vars)) {
  fname = file.path(out_dir, sprintf("w8_netcdf_%s.nc", v))
  londim = ncdim_def("lon", "degrees_east", lons)
  latdim = ncdim_def("lat", "degrees_north", lat)
  timedim = ncdim_def("time", "days since 1900-01-01 00:00:00", time_vals, unlim = FALSE,
                      calendar = "gregorian", create_dimvar = TRUE)
  var = ncvar_def(vars[[v]]$name, vars[[v]]$units, list(londim, latdim, timedim),
                  missval = 32767, prec = "float")
  nc = nc_create(fname, var, force_v4 = FALSE)
  x = round(clim[[v]]$vals * vars[[v]]$mult, 6)
  arr = array(rep(x, each = length(lons)), dim = c(length(lons), 1, length(x)))
  ncvar_put(nc, var, arr)
  ncatt_put(nc, 0, "source", sprintf("Generated by Testing/clim/make_w8_netcdf.R from %s", vars[[v]]$file))
  nc_close(nc)
  cat("Wrote", fname, "\n")
}

base = c(
  "2 grid_cells",
  sprintf("%f location_searching_distance", res),
  "1900 year_start_index",
  "0.0 day_offset",
  "1.0 leap_year_include",
  "0.001 precip_multiplier",
  "C temperature_unit",
  "lon netcdf_var_x",
  "lat netcdf_var_y",
  "clim/w8_netcdf_tmax.nc netcdf_tmax_filename",
  "daily_maximum_temperature netcdf_var_tmax",
  "clim/w8_netcdf_tmin.nc netcdf_tmin_filename",
  "daily_minimum_temperature netcdf_var_tmin",
  "clim/w8_netcdf_rain.nc netcdf_rain_filename",
  "precipitation_amount netcdf_var_rain"
)
# station values taken from the ASCII base station (clim/w8_base)
for (i in seq_along(lons)) {
  base = c(base,
           sprintf("%d base_station_id", 100 + i),
           sprintf("%f lon", lons[i]),
           sprintf("%f lat", lat),
           "975.0 z_coordinate",
           "3.5 effective_lai",
           "160.0 screen_height")
}
writeLines(base, base_out)
cat("Wrote", base_out, "\n")
